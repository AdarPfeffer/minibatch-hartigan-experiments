"""gen_fp_variants.py — generate the float64 and float32 AS-136 variants from as136.f.

WHY GENERATED, NOT HAND-WRITTEN. The experiment asks whether float32 changes Hartigan's
DECISIONS. That only means anything if the two programs are the same program apart from the
floating-point width, so the port must be provably line-for-line. Deriving both variants from
the single source `as136.f` guarantees it: `diff fp_as136_dp.f fp_as136_sp.f` shows the
precision tokens and nothing else, and that diff is the audit.

Both variants:
  * are copies of AS-136 (Hartigan & Wong 1979) as translated by Burkardt — KMNS + OPTRA + QTRAN
  * are renamed (_dp / _sp suffix) so they can coexist in one shared library
  * record every transfer to a shared trace buffer (fp_trace.f), which is the ONLY code added
    to the algorithm. It appends 4 integers at the exact point a transfer is committed; it
    reads no float, changes no branch, and consumes no RNG.
  * leave the production `as136.f` untouched — the running study keeps its own copy.

The float32 variant differs ONLY in:
    double precision -> real        0.0D+00 -> 0.0E+00        1.0D+00 -> 1.0E+00
    dble(...)        -> real(...)   1.0D+30 -> 1.0E+30        r8_huge -> r4_huge_sp
`g_postinit` stays double precision in both: it is a wall-clock reading, not algorithm state,
and demoting it would change the common-block layout rather than the arithmetic.

Run:  python gen_fp_variants.py     (writes fp_as136_dp.f and fp_as136_sp.f)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "as136.f")

# AS-136 proper. `timestamp` is dropped (it is Burkardt's demo helper, not the algorithm).
KEEP = ("kmns", "optra", "qtran", "r8_huge")

# Deliberately identical in both files (no filename, no precision word): the audit inverts
# the precision transform and demands a byte-exact match, so any text that differs between
# the variants — even a comment — has to be a real precision token, not boilerplate.
HEADER = """c  AS-136 (Hartigan & Wong 1979), one of two variants differing only in floating-point width.
c  GENERATED by gen_fp_variants.py from as136.f — do not edit by hand.
c  `make fp-audit` inverts the precision transform and requires a byte-exact match.
c  The only addition to the algorithm is the `call fptrc_add(...)` at each committed
c  transfer, which records (stage, point, from, to) and touches no floating-point state.
"""


def split_units(text):
    """Split the fixed-form source into (unit_name, lines) blocks."""
    units, cur, name = [], [], None
    for ln in text.splitlines(keepends=True):
        m = re.match(r"^      (?:subroutine|function|      function)\s+(\w+)", ln)
        m2 = re.match(r"^      (?:double precision\s+)?function\s+(\w+)", ln)
        hit = m or m2
        if hit:
            if name is not None:
                units.append((name, cur))
            name, cur = hit.group(1).lower(), [ln]
        else:
            if name is None:
                continue                      # leading comments before the first unit
            cur.append(ln)
    if name is not None:
        units.append((name, cur))
    return units


def rename(text, suffix):
    for sub in ("kmns", "optra", "qtran"):
        text = re.sub(rf"\b{sub}\b", f"{sub}_{suffix}", text, flags=re.I)
    return text


def wrap_fixed(text):
    """Re-wrap CODE lines that the rename pushed past column 72.

    Fixed-form Fortran ignores everything after column 72. `kmns` -> `kmns_dp` is 3 characters
    longer, which pushed the trailing `d,` of the KMNS signature to column 73; the comma was
    silently dropped and `d` fused with the continuation line's `itran`, giving the compile
    error `Symbol 'ditran' has no IMPLICIT type`. Truncation is SILENT, so this must be fixed
    at generation time and asserted afterwards (fp_audit.py checks the column limit).

    Comment lines are left alone — a comment is a comment for its whole length, and as136.f
    already ships 20 comment lines past column 72.
    """
    out = []
    for ln in text.splitlines():
        if ln[:1].lower() in ("c", "*", "!") or len(ln) <= 72:
            out.append(ln)
            continue
        while len(ln) > 72:
            cut = ln.rfind(",", 0, 72)          # split after the last comma that still fits
            if cut < 7:                         # nothing sane to split on — leave it for the audit
                break
            out.append(ln[:cut + 1])
            ln = "     &  " + ln[cut + 1:].lstrip()
        out.append(ln)
    return "\n".join(out) + "\n"


def to_single(text):
    out = []
    for ln in text.splitlines(keepends=True):
        # g_postinit is a wall-clock reading, not algorithm state. Leave BOTH its declaration
        # and its assignment in float64 so the common block keeps the same layout and the
        # timing is computed identically — only the algorithm's arithmetic is under test.
        if "g_postinit" in ln:
            out.append(ln)
            continue
        ln = ln.replace("double precision", "real          ")
        ln = ln.replace("0.0D+00", "0.0E+00").replace("1.0D+00", "1.0E+00")
        ln = ln.replace("1.0D+30", "1.0E+30")
        ln = re.sub(r"\bdble\s*\(", "real (", ln)
        ln = re.sub(r"\br8_huge\b", "r4_huge_sp", ln, flags=re.I)
        out.append(ln)
    return "".join(out)


def add_trace(text, unit):
    """Append a trace record where a transfer is committed. l1 = source, l2 = destination."""
    stage = {"optra": 1, "qtran": 2}[unit]
    pat = re.compile(r"^(\s*)(ic1\(i\) = l2\n\s*ic2\(i\) = l1\n)", re.M)
    n = len(pat.findall(text))
    if n != 1:
        raise SystemExit(f"{unit}: expected exactly 1 transfer site, found {n}")
    return pat.sub(lambda m: m.group(0) + f"{m.group(1)}call fptrc_add ( {stage}, i, l1, l2 )\n",
                   text)


def build(suffix, single):
    units = dict(split_units(open(SRC).read()))
    missing = [u for u in KEEP if u not in units]
    if missing:
        raise SystemExit(f"units not found in as136.f: {missing}")
    body = ""
    for u in KEEP:
        src = "".join(units[u])
        if u in ("optra", "qtran"):
            src = add_trace(src, u)
        if u == "r8_huge" and not single:
            src = re.sub(r"\br8_huge\b", "r8_huge_dp", src, flags=re.I)
        body += src
    if not single:                            # keep r8_huge references consistent in dp
        body = re.sub(r"\br8_huge\b", "r8_huge_dp", body, flags=re.I)
    body = rename(body, suffix)
    if single:
        body = to_single(body)
    body = wrap_fixed(body)          # rename can push code past fixed-form column 72
    return HEADER + body


for suffix, single in (("dp", False), ("sp", True)):
    path = os.path.join(HERE, f"fp_as136_{suffix}.f")
    with open(path, "w") as f:
        f.write(build(suffix, single))
    print(f"wrote {path}")
print("\naudit:  diff fp_as136_dp.f fp_as136_sp.f   "
      "(should show ONLY precision tokens and the _dp/_sp renames)")
